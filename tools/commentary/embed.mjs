// Lane A32 (B-to-A-0026 ask 1): embeds B's commentator manifest Game/Plugins/JamAssets/Content/Audio/VO/commentary.json into
// Game/Source/JamGame/Private/CommentaryData.inl as bytes, the way tools/barks/embed.mjs embeds the bark bank, so a packaged game carries the
// manifest without a staging rule in DefaultGame.ini (the Director's preference: no rule to forget). The waves themselves are cooked by the
// +DirectoriesToAlwaysCook=(Path="/JamAssets/Audio/VO") line. The C++ test Jam.Commentary.BankClean fails when the embedded copy differs from the file.
//   node tools/commentary/embed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..', '..');
export const MANIFEST = 'Game/Plugins/JamAssets/Content/Audio/VO/commentary.json';
export const OUTPUT = 'Game/Source/JamGame/Private/CommentaryData.inl';
// Lane A84 (R-0041 point 3): A's supplement (the ability lines; B records the waves later), embedded beside B's manifest and merged by FJamCommentaryBank::Embedded().
export const SUPPLEMENT = 'Game/Content/Commentary/abilities.commentary.json';
export const SUPPLEMENT_OUTPUT = 'Game/Source/JamGame/Private/CommentaryAbilityData.inl';

// The supplement's .inl text (its own array name, so both .inl files can be included in one translation unit).
export function renderSupplement(bytes) {
  return render(bytes).replace(/JamCommentaryBankJson/g, 'JamCommentaryAbilityJson').replace(MANIFEST, SUPPLEMENT);
}

// Renders the .inl text from the manifest bytes (pure, so the test can compare without writing).
export function render(bytes) {
  const rows = [];
  for (let i = 0; i < bytes.length; i += 32) rows.push('\t' + Array.from(bytes.subarray(i, i + 32)).join(',') + ',');
  return `// GENERATED by tools/commentary/embed.mjs from ${MANIFEST}. Do not edit.\n#pragma once\n\n` +
    `static const unsigned char JamCommentaryBankJson[] = {\n${rows.join('\n')}\n\t0\n};\n` +
    `static const unsigned int JamCommentaryBankJsonSize = ${bytes.length};\n`;
}

// The byte array of an .inl text (the test reads the committed copy back).
export function parseInl(text) {
  // \r? : a checkout with autocrlf hands the .inl back with CRLF (the bark test trips on that in a worktree; this one does not).
  const m = text.match(/JamCommentaryBankJson\[\] = \{([\s\S]*?)\r?\n\t0\r?\n\};/);
  if (!m) return null;
  return Buffer.from(m[1].split(/[\s,]+/).filter(Boolean).map(Number));
}

export function embed(root = repo) {
  const bytes = readFileSync(resolve(root, MANIFEST));
  writeFileSync(resolve(root, OUTPUT), render(bytes));
  console.log(`PASS embed commentary ${bytes.length} bytes -> ${OUTPUT}`);
  const sup = readFileSync(resolve(root, SUPPLEMENT));
  writeFileSync(resolve(root, SUPPLEMENT_OUTPUT), renderSupplement(sup));
  console.log(`PASS embed commentary supplement ${sup.length} bytes -> ${SUPPLEMENT_OUTPUT}`);
  return bytes.length;
}

if (process.argv[1] && /embed\.mjs$/.test(process.argv[1].replace(/\\/g, '/'))) embed();
