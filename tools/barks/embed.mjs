// Lane A12: embeds Game/Content/Barks/barks.json into Game/Source/JamGame/Private/BarkData.inl as bytes, the way gen-schema-data.mjs does for the
// schema, so a packaged game carries the bank without a staging rule in DefaultGame.ini (a file lane A12 does not own). The C++ test
// Jam.Barks.BankClean fails when the embedded copy differs from the file on disk.
//   node tools/barks/embed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..', '..');

export function embed() {
  const bytes = readFileSync(resolve(repo, 'Game/Content/Barks/barks.json'));
  const rows = [];
  for (let i = 0; i < bytes.length; i += 32) rows.push('\t' + Array.from(bytes.subarray(i, i + 32)).join(',') + ',');
  const out = '// GENERATED by tools/barks/embed.mjs from Game/Content/Barks/barks.json. Do not edit.\n#pragma once\n\n' +
    `static const unsigned char JamBarkBankJson[] = {\n${rows.join('\n')}\n\t0\n};\n` +
    `static const unsigned int JamBarkBankJsonSize = ${bytes.length};\n`;
  writeFileSync(resolve(repo, 'Game/Source/JamGame/Private/BarkData.inl'), out);
  console.log(`PASS embed barks ${bytes.length} bytes -> Game/Source/JamGame/Private/BarkData.inl`);
  return bytes.length;
}

if (process.argv[1] && /embed\.mjs$/.test(process.argv[1].replace(/\\/g, '/'))) embed();
