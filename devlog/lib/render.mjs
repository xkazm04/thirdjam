// Model to a single self-contained HTML page. Inline CSS, no external requests.
// Every string from outside goes through esc(), which redacts first and escapes second.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { H0_ISO, H0_MS, RULER_HOURS, DEVICES, CLOCK_LABEL } from './constants.mjs';
import { clockLabel, minuteLabel, msAtHour, hourLabel } from './time.mjs';
import { escapeHtml, markdownToHtml } from './markdown.mjs';

const CSS = fs.readFileSync(path.join(path.dirname(fileURLToPath(import.meta.url)), 'style.css'), 'utf8');

const CELL = 28;
const AXIS_H = 66;
const LANE_H = 88;
const MARK_H = 30;
const PAD_R = 24;
const TOTAL_H = AXIS_H + LANE_H * 2 + MARK_H;
const BAR_MAX = 54;

export function fmtCount(n) {
  if (n < 1000) return String(n);
  if (n < 100000) return `${(n / 1000).toFixed(n < 10000 ? 1 : 0).replace(/\.0$/, '')}k`;
  if (n < 1e6) return `${Math.round(n / 1000)}k`;
  return `${(n / 1e6).toFixed(n < 1e7 ? 2 : 1).replace(/\.?0+$/, '')}M`;
}

const plural = (n, one, many = one + 's') => `${n} ${n === 1 ? one : many}`;

export function renderPage(model, opts) {
  const { redact, embed, outDir, title = 'Third Jam dev log', warnings = [], inputs = {}, stats } = opts;
  const esc = (s) => escapeHtml(redact(String(s)));
  const devBadge = (d) => `<span class="dev dev-${esc(d)}" title="Device ${esc(d)}">${esc(d)}</span>`;
  const S = model.summary;

  // ---------- masthead + strip ----------
  const tok = S.tokens;
  const tokenIn = tok.input + tok.cacheWrite;
  const strip = [
    ['Commits', fmtCount(S.commits), 'across both devices'],
    [
      'Agent sessions',
      fmtCount(S.sessions.main + S.sessions.subagent),
      `${S.sessions.main} main, ${S.sessions.subagent} subagent`,
    ],
    ['Agent turns', fmtCount(S.turns), S.prompts ? `${fmtCount(S.prompts)} human prompts` : 'model responses'],
    ['Tokens in', tok.any ? fmtCount(tokenIn) : 'n/a', tok.any ? `plus ${fmtCount(tok.cacheRead)} read from cache` : 'no usage in transcripts'],
    ['Tokens out', tok.any ? fmtCount(tok.output) : 'n/a', 'generated by models'],
    ['Screenshots', fmtCount(S.shots), 'from the editor and the build'],
  ]
    .map(([k, v, sub]) => `<div><dt class="label">${esc(k)}</dt><dd><span class="big">${esc(v)}</span><span class="sub">${esc(sub)}</span></dd></div>`)
    .join('');

  const h0Label = clockLabel(H0_MS);
  const hd = new Date(H0_MS + 3600000);
  const h0Date = `${hd.getUTCDate()} ${['January','February','March','April','May','June','July','August','September','October','November','December'][hd.getUTCMonth()]} ${hd.getUTCFullYear()}`;
  const asOf =
    S.lastMs === undefined
      ? 'No entries yet.'
      : `Latest entry ${hourLabel(Math.max(0, Math.round(S.asOfHour * 10) / 10))}${S.asOfHour < 0 ? ' (before the start)' : ''}, ${clockLabel(S.lastMs)}.`;

  // ---------- ruler ----------
  const W = RULER_HOURS * CELL + PAD_R;
  const x = (h) => h * CELL;
  const laneTop = (i) => AXIS_H + i * LANE_H;
  const maxTurns = Math.max(1, ...DEVICES.map((d) => model.peak[d]));
  let svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${TOTAL_H}" viewBox="0 0 ${W} ${TOTAL_H}" role="img" aria-label="Timeline of the build from H0 to H${RULER_HOURS}, two lanes, one per device. The journal below lists the same entries as text.">`;
  // lane backgrounds
  svg += `<rect class="lane-a-bg" x="0" y="${laneTop(0)}" width="${W}" height="${LANE_H}"/>`;
  svg += `<rect class="lane-b-bg" x="0" y="${laneTop(1)}" width="${W}" height="${LANE_H}"/>`;
  // six-hour grid
  for (let h = 0; h <= RULER_HOURS; h += 6) svg += `<line class="grid6" x1="${x(h)}" y1="${AXIS_H}" x2="${x(h)}" y2="${TOTAL_H}"/>`;
  // axis
  svg += `<line class="tick major" x1="0" y1="${AXIS_H}" x2="${x(RULER_HOURS)}" y2="${AXIS_H}"/>`;
  for (let h = 0; h <= RULER_HOURS; h++) {
    const major = h % 6 === 0;
    svg += `<line class="tick${major ? ' major' : ''}" x1="${x(h)}" y1="${AXIS_H - (major ? 9 : 5)}" x2="${x(h)}" y2="${AXIS_H}"/>`;
    if (major) svg += `<text class="hlabel" x="${x(h) + (h === 0 ? 0 : 0)}" y="${AXIS_H - 14}" text-anchor="${h === 0 ? 'start' : 'middle'}">H${h}</text>`;
  }
  // day names at midnight (CET); the first one sits at H0
  const dayAt = [{ h: 0, label: clockLabel(H0_MS, false).slice(0, 3) }];
  for (let h = 18; h < RULER_HOURS; h += 24) dayAt.push({ h, label: clockLabel(msAtHour(h), false).slice(0, 3) });
  for (const d of dayAt) svg += `<text class="daylabel" x="${x(d.h) + 4}" y="${AXIS_H - 30}">${esc(d.label)}</text>`;
  // lanes: turn bars + commit pills
  DEVICES.forEach((d, i) => {
    const top = laneTop(i);
    const base = top + 68;
    const cls = d.toLowerCase();
    model.ruler.forEach((r, h) => {
      const c = r[d];
      if (c.turns) {
        const bh = Math.max(2, Math.round((c.turns / maxTurns) * BAR_MAX));
        svg += `<rect class="bar-${cls}" x="${x(h) + 5}" y="${base - bh}" width="${CELL - 10}" height="${bh}" rx="1.5"/>`;
      }
      if (c.commits) {
        svg += `<rect class="pill-${cls}" x="${x(h) + 3}" y="${top + 73}" width="${CELL - 6}" height="13" rx="6.5"/>`;
        svg += `<text class="pilltext-${cls}" x="${x(h) + CELL / 2}" y="${top + 83}" text-anchor="middle">${c.commits}</text>`;
      }
    });
  });
  // gates
  const gates = model.gates.filter((g) => g.hour >= 0 && g.hour <= RULER_HOURS);
  gates.forEach((g, i) => {
    const gx = x(g.hour);
    const ty = 12 + (i % 2) * 14;
    svg += `<line class="gate-line" x1="${gx}" y1="${ty + 3}" x2="${gx}" y2="${AXIS_H - 36}"/><line class="gate-line" x1="${gx}" y1="${AXIS_H}" x2="${gx}" y2="${TOTAL_H}"/>`;
    svg += `<polygon class="gate-flag" points="${gx},${ty - 8} ${gx + 5},${ty - 4} ${gx},${ty}"/>`;
    const flip = gx > W - 120;
    svg += `<text class="gate-text" x="${flip ? gx - 7 : gx + 8}" y="${ty}" text-anchor="${flip ? 'end' : 'start'}">${esc(g.name)}<title>${esc(`${g.name} at ${hourLabel(g.hour)}${g.sub ? ': ' + g.sub : ''}`)}</title></text>`;
  });
  // marks row: shots (circles), notes (squares), status (rings)
  const my = AXIS_H + LANE_H * 2 + MARK_H / 2;
  for (const [i, e] of model.hours.entries()) {
    if (typeof e.hour !== 'number' || e.hour >= RULER_HOURS) continue;
    const cx = x(e.hour) + CELL / 2;
    let off = 0;
    const slots = [];
    // B-to-A-0013: one note mark per device that wrote this hour (a note without a device counts as A's).
    for (const dv of DEVICES) if (e.notes.some((n) => (n.device || 'A') === dv)) slots.push('note-' + dv.toLowerCase());
    for (const dv of DEVICES) if (e.shots.some((s) => s.device === dv)) slots.push('shot-' + dv.toLowerCase());
    if (e.status.length) slots.push('status');
    const start = cx - ((slots.length - 1) * 8) / 2;
    for (const sl of slots) {
      const px = start + off;
      off += 8;
      if (sl.startsWith('note-')) svg += `<rect class="mk-note mk-note-${sl.slice(-1)}" x="${px - 3.5}" y="${my - 3.5}" width="7" height="7" rx="1"/>`;
      else if (sl === 'status') svg += `<circle class="mk-status" cx="${px}" cy="${my}" r="3.5"/>`;
      else svg += `<circle class="mk-shot-${sl.slice(-1)}" cx="${px}" cy="${my}" r="4.5"/>`;
    }
    void i;
  }
  // latest-entry cursor
  if (S.asOfHour !== undefined && S.asOfHour >= 0 && S.asOfHour < RULER_HOURS) {
    const ax = x(S.asOfHour);
    svg += `<line class="asof-line" x1="${ax}" y1="${AXIS_H}" x2="${ax}" y2="${TOTAL_H}"/>`;
    const flip = ax > W - 70;
    svg += `<text class="asof-text" x="${flip ? ax - 5 : ax + 5}" y="${TOTAL_H - 4}" text-anchor="${flip ? 'end' : 'start'}">latest</text>`;
  }
  // hour hit areas link to the journal
  for (const e of model.hours) {
    if (typeof e.hour !== 'number' || e.hour >= RULER_HOURS) continue;
    const r = model.ruler[e.hour];
    const tip = `H${e.hour}, ${clockLabel(msAtHour(e.hour))}: ` + DEVICES.map((d) => `${d} ${plural(r[d].turns, 'turn')}, ${plural(r[d].commits, 'commit')}`).join('; ');
    svg += `<a href="#h${e.hour}" aria-label="${esc(tip)}"><rect class="hit" x="${x(e.hour)}" y="0" width="${CELL}" height="${TOTAL_H}"><title>${esc(tip)}</title></rect></a>`;
  }
  svg += '</svg>';

  const laneLabel = (cls, d) =>
    `<div class="${cls}" style="height:${LANE_H}px"><strong>${d}</strong>${model.peak[d] ? `peak ${model.peak[d]} turns/h` : 'no turns yet'}</div>`;
  const ruler = `
<div class="ruler">
  <div class="ruler-labels" aria-hidden="true"><div style="height:${AXIS_H}px"><span>hour<br>since H0</span></div>${laneLabel('la', 'A')}${laneLabel('lb', 'B')}<div style="height:${MARK_H}px"><span>marks</span></div></div>
  <div class="ruler-scroll" id="ruler-scroll" tabindex="0" role="region" aria-label="Build timeline, scrolls sideways">${svg}</div>
</div>
<ul class="legend" aria-hidden="true">
  <li><svg viewBox="0 0 14 14"><rect x="3" y="4" width="8" height="9" fill="currentColor" class="swatch-a"/></svg>Agent turns per hour, device A</li>
  <li><svg viewBox="0 0 14 14"><rect x="3" y="4" width="8" height="9" fill="currentColor" class="swatch-b"/></svg>device B</li>
  <li><svg viewBox="0 0 14 14"><rect x="1" y="2" width="12" height="10" rx="5" fill="none" stroke="currentColor" stroke-width="1.5"/></svg>Commits per hour</li>
  <li><svg viewBox="0 0 14 14"><circle cx="7" cy="7" r="4.5" fill="currentColor"/></svg>Screenshot</li>
  <li><svg viewBox="0 0 14 14"><rect x="3.5" y="3.5" width="7" height="7" rx="1" fill="currentColor"/></svg>Note</li>
  <li><svg viewBox="0 0 14 14"><circle cx="7" cy="7" r="3.5" fill="none" stroke="currentColor" stroke-width="1.5"/></svg>Status report</li>
  <li><svg viewBox="0 0 14 14"><path d="M3 1 L11 5 L3 9 Z M3 1 V13" fill="currentColor" stroke="currentColor"/></svg>Gate</li>
</ul>`;

  // ---------- journal ----------
  const src = (s) => {
    if (embed) {
      try {
        return `data:${s.mime};base64,${fs.readFileSync(s.file).toString('base64')}`;
      } catch {
        return undefined;
      }
    }
    const rel = path.relative(outDir, s.file).split(path.sep).map(encodeURIComponent).join('/');
    return rel;
  };
  const commitList = (list) => {
    const li = (c) =>
      `<li>${devBadge(c.device)}<code class="sha">${esc(c.hash)}</code><span class="subj">${esc(c.subject)}</span><time datetime="${new Date(c.ms).toISOString()}">${esc(minuteLabel(c.ms))}</time></li>`;
    if (list.length <= 10) return `<ul class="commits">${list.map(li).join('')}</ul>`;
    return `<ul class="commits">${list.slice(0, 8).map(li).join('')}</ul><details class="more"><summary>${list.length - 8} more commits this hour</summary><ul class="commits">${list.slice(8).map(li).join('')}</ul></details>`;
  };
  const shotFig = (s) => {
    const u = src(s);
    const dims = s.size ? ` width="${s.size.w}" height="${s.size.h}"` : '';
    const img = u
      ? `<img src="${u}"${dims} alt="${esc(s.caption)}" loading="lazy" decoding="async">`
      : `<div class="ph">image file unreadable</div>`;
    return `<figure class="shot shot-${esc(s.device)}">${img}<figcaption>${devBadge(s.device)}<span>${esc(s.caption)}</span><time datetime="${new Date(s.ms).toISOString()}">${esc(minuteLabel(s.ms))}</time></figcaption></figure>`;
  };
  const statusCard = (st) =>
    `<div class="status-card"><h5>${devBadge(st.device)} Status ${esc(hourLabel(st.hour))}${st.heading ? ' &middot; ' + esc(st.heading) : ''}</h5><dl>${st.fields.map((f) => `<dt>${esc(f.key)}</dt><dd>${esc(f.value)}</dd>`).join('')}</dl></div>`;

  const hourSection = (e) => {
    const h = e.hour;
    const meta = e.perDevice
      ? DEVICES.map((d) => {
          const c = e.perDevice[d];
          const bits = [];
          if (c.turns) bits.push(plural(c.turns, 'turn'));
          if (c.commits) bits.push(plural(c.commits, 'commit'));
          return bits.length ? `<li>${devBadge(d)}<span>${bits.join(', ')}</span></li>` : '';
        }).join('')
      : '';
    const body = [];
    for (const g of e.gates) body.push(`<div class="gate-banner"><strong>${esc(g.name)}</strong>${g.sub ? ' &middot; ' + esc(g.sub) : ''}</div>`);
    for (const n of e.notes) {
      // B-to-A-0013: a note carries its device (notes.md A, notes-b.md B); the badge keeps the lane visible in the journal.
      const nd = n.device || 'A';
      body.push(`<article class="note note-${esc(nd.toLowerCase())}">${n.title ? `<h4>${devBadge(nd)} ${esc(n.title)}</h4>` : devBadge(nd)}${markdownToHtml(n.body, redact)}</article>`);
    }
    if (e.shots.length) body.push(`<div class="shots">${e.shots.map(shotFig).join('')}</div>`);
    if (e.status.length) body.push(`<div class="status">${e.status.map(statusCard).join('')}</div>`);
    if (e.commits.length) body.push(commitList(e.commits));
    return `<section class="hour" id="h${h}" aria-labelledby="h${h}-t">
  <header class="hour-head"><h3 id="h${h}-t"><span class="hnum">H${h}</span><span class="clock">${esc(clockLabel(msAtHour(h)))}</span></h3>${meta ? `<ul class="hour-meta">${meta}</ul>` : ''}</header>
  <div class="hour-body">${body.join('\n')}</div>
</section>`;
  };

  const outsideBlock = (key, heading) => {
    const o = model.outside[key];
    if (!o.commits.length && !o.shots.length && !o.turns && !o.prompts) return '';
    const bits = [];
    if (o.commits.length) bits.push(plural(o.commits.length, 'commit'));
    if (o.turns) bits.push(plural(o.turns, 'agent turn'));
    if (o.shots.length) bits.push(plural(o.shots.length, 'screenshot'));
    return `<details class="outside" id="${key}"><summary>${esc(heading)}<span class="label">${esc(bits.join(' · '))}</span></summary>${o.shots.length ? `<div class="shots">${o.shots.map(shotFig).join('')}</div>` : ''}${o.commits.length ? commitList(o.commits) : ''}</details>`;
  };

  const journalHtml =
    model.hours.length || outsideBlock('pre', 'x') || outsideBlock('post', 'x')
      ? `${outsideBlock('pre', 'Before H0: preparation (tools, schema, prompts and scripts only)')}<div class="journal">${model.hours.map(hourSection).join('\n')}</div>${outsideBlock('post', `After H${RULER_HOURS}`)}`
      : `<p class="empty">Nothing recorded yet. Entries appear here as commits land, agents work, screenshots are captured and notes are written.</p>`;

  // ---------- sessions ----------
  const sess = [...model.sessions].sort((a, b) => (a.firstMs ?? 0) - (b.firstMs ?? 0));
  const sessionsHtml = sess.length
    ? `<section class="block" id="sessions"><h2>Agent sessions</h2><p class="lede">Every transcript that went into the counts above. Prompt text is never shown here.</p><div class="table-wrap"><table class="sessions"><thead><tr><th>Dev</th><th>Kind</th><th>Session</th><th>Started</th><th class="r">Turns</th><th class="r">Tokens out</th></tr></thead><tbody>${sess
        .map((s) => {
          const out = s.turns.reduce((a, t) => a + t.usage.output, 0);
          const started = s.firstMs === undefined ? 'unknown' : `${hourLabel(Math.round(((s.firstMs - H0_MS) / 3600000) * 10) / 10)} · ${clockLabel(s.firstMs, false)}`;
          return `<tr><td>${devBadge(s.device)}</td><td>${esc(s.kind)}</td><td class="title">${esc(s.title || 'untitled')}<br><span class="id num">${esc(s.id)}</span></td><td class="num">${esc(started)}</td><td class="r num">${s.turns.length}</td><td class="r num">${out ? esc(fmtCount(out)) : '–'}</td></tr>`;
        })
        .join('')}</tbody></table></div></section>`
    : '';

  // ---------- colophon ----------
  const r = stats || { key: 0, email: 0, path: 0 };
  const warn = warnings.length ? `<ul class="warnings">${warnings.map((w) => `<li>${esc(w)}</li>`).join('')}</ul>` : '';
  const colophon = `<footer class="colophon"><p>Built by <code>devlog/build.mjs</code> from ${plural(inputs.transcripts || 0, 'transcript file')}, ${plural(inputs.repos || 0, 'repository', 'repositories')}, ${plural(inputs.shots || 0, 'screenshot')}, ${plural(inputs.notes || 0, 'note')} and ${plural(inputs.status || 0, 'status entry', 'status entries')}. Hours count from H0, ${esc(H0_ISO)}. Times are ${CLOCK_LABEL}.</p><p>Redaction pass: ${plural(r.key, 'secret')}, ${plural(r.email, 'email address', 'email addresses')} and ${plural(r.path, 'home-directory path')} removed before this page was written. Token counts come from the usage fields of the transcripts; turns are model responses, counted once each.</p>${warn}</footer>`;

  const script = `<script>try{var s=document.getElementById('ruler-scroll');var l=s&&s.querySelector('.asof-line');if(s&&l){var x=+l.getAttribute('x1');s.scrollLeft=Math.max(0,x-s.clientWidth*0.6);}}catch(e){}</script>`;

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<title>${esc(title)}</title>
<meta name="description" content="A timeline of the build: commits, agent turns, screenshots and notes, hour by hour.">
<style>${CSS}</style>
</head>
<body>
<main class="wrap">
<header class="masthead">
  <p class="label">Epic AI MegaJam 2026 &middot; Unreal Engine track</p>
  <h1>${esc(title).replace(/^(.*?)(dev log)$/i, '$1<em>$2</em>')}</h1>
  <p class="deck">The build as it happened: agent turns, commits, editor screenshots and notes, hour by hour on two devices. Hour 0 is ${esc(h0Label)} on ${esc(h0Date)}. ${esc(asOf)}</p>
  <dl class="strip">${strip}</dl>
</header>
<section class="block" id="timeline"><h2>The ninety-three hours</h2><p class="lede">Bars are agent turns per hour, pills are commits, dashed lines are the gates. Select an hour to jump to its entry.</p>${ruler}</section>
<section class="block" id="journal"><h2>Hour by hour</h2><p class="lede">Notes, screenshots, status reports and commits, in the order they happened.</p>${journalHtml}</section>
${sessionsHtml}
${colophon}
</main>
${script}
</body>
</html>
`;
}
