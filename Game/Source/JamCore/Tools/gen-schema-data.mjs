// Embeds schema/cartridge.schema.json, schema/game.schema.json and schema/limits.json into the C++ loader so a packaged
// game validates cartridges with exactly the files Node uses. Run after any schema change:
//   node Game/Source/JamCore/Tools/gen-schema-data.mjs
// The CartridgeRoundTrip test fails when the embedded copy differs from schema/ on disk.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..', '..', '..', '..');
const files = ['cartridge.schema.json', 'game.schema.json', 'limits.json'];
let out = '// GENERATED by Game/Source/JamCore/Tools/gen-schema-data.mjs from schema/*.json. Do not edit.\n#pragma once\n\n';
const names = [];
for (const f of files) {
  const bytes = readFileSync(resolve(repo, 'schema', f));
  const id = 'JamSchema_' + f.replace(/[^A-Za-z0-9]/g, '_');
  names.push([f, id]);
  const rows = [];
  for (let i = 0; i < bytes.length; i += 32) rows.push('\t' + Array.from(bytes.subarray(i, i + 32)).join(',') + ',');
  out += `static const unsigned char ${id}[] = {\n${rows.join('\n')}\n\t0\n};\n\n`;
}
out += 'struct FJamEmbeddedSchemaFile { const TCHAR* Name; const unsigned char* Data; };\n';
out += 'static const FJamEmbeddedSchemaFile JamEmbeddedSchemaFiles[] = {\n' + names.map(([f, id]) => `\t{ TEXT("${f}"), ${id} },`).join('\n') + '\n};\n';
writeFileSync(resolve(here, '..', 'Private', 'JamSchemaData.inl'), out);
console.log(`PASS gen-schema-data ${files.length} files`);
