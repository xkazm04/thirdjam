// Lane A14: embeds Game/Content/Designer/builtin-effects.json into the JamCore module (a packaged game has no repo folders).
//   node Game/Source/JamCore/Effects/gen-builtin-effects.mjs
// Also checks that every entry is a valid game.effects item (under another id, since built-in ids are reserved). Exit 1 when not.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateCartridge, BUILTIN_EFFECTS } from '../../../../schema/validate.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..', '..', '..', '..');
const src = resolve(repo, 'Game/Content/Designer/builtin-effects.json');
const text = readFileSync(src, 'utf8');
const data = JSON.parse(text);
const base = JSON.parse(readFileSync(resolve(repo, 'Game/Content/Cartridges/hockey.regular.cartridge.json'), 'utf8'));
let bad = 0;
if (JSON.stringify(data.effects.map((e) => e.id)) !== JSON.stringify(BUILTIN_EFFECTS)) { bad += 1; console.log('FAIL builtin ids must be exactly ' + BUILTIN_EFFECTS.join(', ')); }
for (const e of data.effects) {
  const { magnitude_stats, inverse_magnitude_stats, ...def } = e;
  const c = JSON.parse(JSON.stringify(base));
  c.game.effects = [{ ...def, id: `x-${def.id.replace(/_/g, '-')}` }];
  const r = validateCartridge(c);
  if (!r.ok) { bad += 1; console.log(`FAIL builtin ${def.id}`); for (const err of r.errors) console.log(`  ${err}`); }
}
if (bad) { console.log(JSON.stringify({ tool: 'gen-builtin-effects', ok: false, bad })); process.exit(1); }
const bytes = Buffer.from(text, 'utf8');
const rows = [];
for (let i = 0; i < bytes.length; i += 32) rows.push('\t' + Array.from(bytes.subarray(i, i + 32)).join(',') + ',');
const out = '// GENERATED by Game/Source/JamCore/Effects/gen-builtin-effects.mjs from Game/Content/Designer/builtin-effects.json. Do not edit.\n#pragma once\n\n'
  + `static const unsigned char JamBuiltinEffectsJson[] = {\n${rows.join('\n')}\n\t0\n};\n`;
writeFileSync(resolve(here, 'BuiltinEffectsData.inl'), out);
console.log(`PASS gen-builtin-effects ${data.effects.length} effects, ${bytes.length} bytes`);
console.log(JSON.stringify({ tool: 'gen-builtin-effects', ok: true, effects: data.effects.length }));
